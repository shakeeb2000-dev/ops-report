def huffman_codes(bits, vals):
    """Canonical JPEG code assignment: returns {symbol: (code, length)}."""
    codes = {}
    code = 0
    k = 0
    for length in range(1, 17):
        for _ in range(bits[length - 1]):
            codes[vals[k]] = (code, length)
            code += 1
            k += 1
        code <<= 1
    return codes


class BitWriter:
    def __init__(self):
        self.out = bytearray()
        self.acc = 0
        self.n = 0

    def write(self, code, length):
        for i in range(length - 1, -1, -1):
            self.acc = (self.acc << 1) | ((code >> i) & 1)
            self.n += 1
            if self.n == 8:
                self._flush_byte(self.acc & 0xFF)
                self.acc = 0
                self.n = 0

    def _flush_byte(self, b):
        self.out.append(b)
        if b == 0xFF:
            self.out.append(0x00)  # byte stuffing

    def finish(self):
        while self.n:
            self.acc = (self.acc << 1) | 1
            self.n += 1
            if self.n == 8:
                self._flush_byte(self.acc & 0xFF)
                self.acc = 0
                self.n = 0
        return bytes(self.out)


def dht_segment(class_id, table_id, bits, vals):
    payload = bytes([(class_id << 4) | table_id]) + bytes(bits) + bytes(vals)
    return b"\xFF\xC4" + struct.pack(">H", len(payload) + 2) + payload


def build(width, height):
    quant = bytes([16] * 64)  # flat table; DC of 0 stays 0 regardless

    out = bytearray()
    out += b"\xFF\xD8"  # SOI

    jfif = b"JFIF\x00" + bytes([1, 1, 0]) + struct.pack(">HH", 1, 1) + bytes([0, 0])
    out += b"\xFF\xE0" + struct.pack(">H", len(jfif) + 2) + jfif

    for tid in (0, 1):
        payload = bytes([tid]) + quant
        out += b"\xFF\xDB" + struct.pack(">H", len(payload) + 2) + payload

    # SOF0 baseline, 3 components, no subsampling (4:4:4)
    comps = b""
    for cid in (1, 2, 3):
        comps += bytes([cid, 0x11, 0 if cid == 1 else 1])
    sof = bytes([8]) + struct.pack(">HH", height, width) + bytes([3]) + comps
    out += b"\xFF\xC0" + struct.pack(">H", len(sof) + 2) + sof

    out += dht_segment(0, 0, DC_LUM_BITS, DC_LUM_VALS)
    out += dht_segment(1, 0, AC_LUM_BITS, AC_LUM_VALS)
    out += dht_segment(0, 1, DC_CHR_BITS, DC_CHR_VALS)
    out += dht_segment(1, 1, AC_CHR_BITS, AC_CHR_VALS)

    sos = bytes([3, 1, 0x00, 2, 0x11, 3, 0x11, 0, 63, 0])
    out += b"\xFF\xDA" + struct.pack(">H", len(sos) + 2) + sos

    dc_lum = huffman_codes(DC_LUM_BITS, DC_LUM_VALS)
    ac_lum = huffman_codes(AC_LUM_BITS, AC_LUM_VALS)
    dc_chr = huffman_codes(DC_CHR_BITS, DC_CHR_VALS)
    ac_chr = huffman_codes(AC_CHR_BITS, AC_CHR_VALS)

    mcus_x = (width + 7) // 8
    mcus_y = (height + 7) // 8

    bw = BitWriter()
    for _ in range(mcus_x * mcus_y):
        # Y block: DC category 0 (delta 0), then EOB
        bw.write(*dc_lum[0])
        bw.write(*ac_lum[0x00])
        # Cb, Cr blocks
        for _ in range(2):
            bw.write(*dc_chr[0])
            bw.write(*ac_chr[0x00])
    out += bw.finish()

    out += b"\xFF\xD9"  # EOI
    return bytes(out)


if __name__ == "__main__":
    w = int(sys.argv[1]) if len(sys.argv) > 1 else 640
    h = int(sys.argv[2]) if len(sys.argv) > 2 else 480
    path = sys.argv[3] if len(sys.argv) > 3 else "test.jpg"
    data = build(w, h)
    with open(path, "wb") as fh:
        fh.write(data)
    print(f"wrote {path}: {w}x{h}, {len(data)} bytes")
